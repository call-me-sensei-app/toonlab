import fs from 'node:fs';
import path from 'node:path';

const ROOT_DIR = process.cwd();
const MODELS_DIR = path.join(ROOT_DIR, 'assets-local/models');
const OUTPUT_FILE = path.join(ROOT_DIR, 'labs/shared/localCharacterAssets.generated.js');

const CHARACTER_MODEL_EXTENSIONS = new Set(['.pmx', '.pmd', '.fbx', '.glb', '.gltf', '.obj', '.usdz']);
const CHARACTER_MATERIAL_EXTENSIONS = new Set(['.mtl']);
const MODEL_TEXTURE_EXTENSIONS = new Set([
  '.bmp',
  '.gif',
  '.jpeg',
  '.jpg',
  '.ktx',
  '.ktx2',
  '.png',
  '.spa',
  '.sph',
  '.tga',
  '.webp',
]);

function projectUrlForPath(absolutePath) {
  return `/${path.relative(ROOT_DIR, absolutePath).split(path.sep).join('/')}`;
}

function collectFiles(rootDirectory, extensions) {
  const results = [];
  if (!fs.existsSync(rootDirectory)) return results;

  const stack = [rootDirectory];
  while (stack.length > 0) {
    const directory = stack.pop();
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolutePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        stack.push(absolutePath);
        continue;
      }
      if (!entry.isFile() || !extensions.has(path.extname(entry.name).toLowerCase())) continue;
      results.push(projectUrlForPath(absolutePath));
    }
  }

  return results.sort((a, b) => a.localeCompare(b));
}

const manifest = {
  materialPaths: collectFiles(MODELS_DIR, CHARACTER_MATERIAL_EXTENSIONS),
  modelPaths: collectFiles(MODELS_DIR, CHARACTER_MODEL_EXTENSIONS),
  texturePaths: collectFiles(MODELS_DIR, MODEL_TEXTURE_EXTENSIONS),
};

const contents = `// Generated by scripts/generate-local-character-assets.mjs.
// This file is ignored by git because assets-local/models is local drop-in data.

export const modelPaths = ${JSON.stringify(manifest.modelPaths, null, 2)};
export const materialPaths = ${JSON.stringify(manifest.materialPaths, null, 2)};
export const texturePaths = ${JSON.stringify(manifest.texturePaths, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, contents);
console.log(
  `Wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)} ` +
  `(${manifest.modelPaths.length} models, ${manifest.materialPaths.length} materials, ${manifest.texturePaths.length} textures).`,
);
