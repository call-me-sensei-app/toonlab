import fs from 'node:fs';
import path from 'node:path';

const ROOT_DIR = process.cwd();
const ENVIRONMENT_ROOTS = [
  path.join(ROOT_DIR, 'assets-local/environments/examples'),
  path.join(ROOT_DIR, 'assets-local/environments/tests'),
];
const OUTPUT_FILE = path.join(ROOT_DIR, 'labs/shared/localEnvironmentAssets.generated.js');

const ENVIRONMENT_MODEL_EXTENSIONS = new Set(['.fbx', '.glb', '.gltf', '.obj', '.usdz']);
const ENVIRONMENT_IMAGE_EXTENSIONS = new Set([
  '.avif',
  '.bmp',
  '.jpeg',
  '.jpg',
  '.ktx',
  '.ktx2',
  '.png',
  '.tga',
  '.webp',
]);

function projectUrlForPath(absolutePath) {
  return `/${path.relative(ROOT_DIR, absolutePath).split(path.sep).join('/')}`;
}

function pathContainsSegment(absolutePath, segmentName) {
  return absolutePath.split(path.sep).includes(segmentName);
}

function collectFiles(rootDirectories, predicate) {
  const results = [];

  for (const rootDirectory of rootDirectories) {
    if (!fs.existsSync(rootDirectory)) continue;

    const stack = [rootDirectory];
    while (stack.length > 0) {
      const directory = stack.pop();
      for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        const absolutePath = path.join(directory, entry.name);
        if (entry.isDirectory()) {
          stack.push(absolutePath);
          continue;
        }
        if (!entry.isFile() || !predicate(absolutePath)) continue;
        results.push(projectUrlForPath(absolutePath));
      }
    }
  }

  return results.sort((a, b) => a.localeCompare(b));
}

const modelPaths = collectFiles(ENVIRONMENT_ROOTS, (absolutePath) => (
  ENVIRONMENT_MODEL_EXTENSIONS.has(path.extname(absolutePath).toLowerCase()) &&
  pathContainsSegment(absolutePath, 'models')
));
const backgroundPaths = collectFiles(ENVIRONMENT_ROOTS, (absolutePath) => (
  ENVIRONMENT_IMAGE_EXTENSIONS.has(path.extname(absolutePath).toLowerCase()) &&
  pathContainsSegment(absolutePath, 'backgrounds')
));
const texturePaths = collectFiles(ENVIRONMENT_ROOTS, (absolutePath) => (
  ENVIRONMENT_IMAGE_EXTENSIONS.has(path.extname(absolutePath).toLowerCase()) &&
  pathContainsSegment(absolutePath, 'models')
));

const contents = `// Generated by scripts/generate-local-environment-assets.mjs.
// This file is ignored by git because assets-local/environments/tests is local test data.

export const modelPaths = ${JSON.stringify(modelPaths, null, 2)};
export const backgroundPaths = ${JSON.stringify(backgroundPaths, null, 2)};
export const texturePaths = ${JSON.stringify(texturePaths, null, 2)};
`;

fs.writeFileSync(OUTPUT_FILE, contents);
console.log(
  `Wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)} ` +
  `(${modelPaths.length} models, ${backgroundPaths.length} backgrounds, ${texturePaths.length} textures).`,
);
