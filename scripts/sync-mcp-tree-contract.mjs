import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { recipeFromSettings, TREE_SETTING_DEFAULTS, TREE_SETTING_FIELD_SCHEMA } from '../src/vegetation/treeRecipe.js';

// MCP needs portable authoring data, not the repository-only geometry engines.
const path = new URL('../mcp/tree-lab-contract.mjs', import.meta.url);
const source = '// Generated by scripts/sync-mcp-tree-contract.mjs.\nexport const treeContract = ' + JSON.stringify({
  starter: recipeFromSettings(TREE_SETTING_DEFAULTS),
  fields: TREE_SETTING_FIELD_SCHEMA,
}, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  assert.equal(await readFile(path, 'utf8'), source, 'Refresh the MCP tree authoring contract with node scripts/sync-mcp-tree-contract.mjs');
} else {
  await writeFile(path, source);
}
